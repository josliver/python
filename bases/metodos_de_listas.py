lista = list(["a", "b", "c", "d", "e"])

print(len(lista)) # devuelve la longitud de la lista
print(lista[0]) # devuelve el primer elemento de la lista
print(lista.append("f")) # agrega un elemento al final de la lista
print(lista.insert(0, "z")) # agrega un elemento en la posicion 0 de la lista
print(lista.remove("c")) # elimina el elemento "c" de la lista
print(lista.pop()) # elimina el ultimo elemento de la lista y lo devuelve
print(lista)