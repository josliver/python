# Operadores aritméticos
suma = 2 + 5
resta = 5 - 2
multiplicacion = 5 * 2
division = 5 / 2 # devuelve un float
division_entera = 5 // 2 # devuelve un int
modulo = 5 % 2 # devuelve el resto de la division       
exponente = 5 ** 2 # devuelve 25, 5 elevado a la potencia de 2

print(suma)
print(resta)
print(multiplicacion)
print(division)
print(division_entera)
print(modulo)
print(exponente)

tipo_de_dato = type(division)
print(tipo_de_dato)

#Operadores de comparación
a = 5
b = 6
print(a == b) # False
print(a != b) # True
print(a > b) # False
print(a < b) # True
print(a >= b) # False
print(a <= b) # True

#Operadores logicos
a = True
b = False
print(a and b) # False
print(a or b) # True
print(not a) # False

print(a & b) # False
print(a | b) # True
# Operador XOR
print(a ^ b) # True
